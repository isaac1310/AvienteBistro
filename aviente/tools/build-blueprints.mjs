#!/usr/bin/env node
/**
 * design/blueprints/*.svg → lib/blueprints.generated.ts
 *
 * The drawings have to be INLINE in the page: they are stroked with `currentColor`,
 * and an SVG loaded as an <img> or a background-image is rendered in isolation, so
 * currentColor resolves to black there instead of the theme's ink. (The header's
 * utensil field lost a day to exactly that.)
 *
 * Generated into a TS module rather than read with fs at request time, because a
 * runtime file read has to be traced into the serverless bundle to survive deploy,
 * and a committed module simply cannot fail. The .svg files stay the source of truth
 * so the drawings can keep being iterated on in a design tool.
 *
 *   npm run blueprints
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = new URL('../design/blueprints/', import.meta.url).pathname;
const OUT = new URL('../lib/blueprints.generated.ts', import.meta.url).pathname;

const KEYS = ['entrees', 'soups', 'salads', 'mains', 'sides', 'breads', 'desserts', 'kids', 'other'];

const files = readdirSync(SRC).filter((f) => f.endsWith('.svg'));
const found = new Map(files.map((f) => [f.replace(/\.svg$/, ''), f]));

const missing = KEYS.filter((k) => !found.has(k));
if (missing.length) {
  console.error(`missing a blueprint for: ${missing.join(', ')}`);
  process.exit(1);
}
const extra = [...found.keys()].filter((k) => !KEYS.includes(k));
if (extra.length) console.warn(`ignored (not a category): ${extra.join(', ')}`);

const entries = KEYS.map((key) => {
  /* Only the inner markup is kept. The wrapper <svg> is re-emitted by the component
     so its size and stroke weight are the component's business -- the README asks for
     a heavier stroke at thumbnail size, which cannot be done from inside the file. */
  const raw = readFileSync(join(SRC, found.get(key)), 'utf8');
  const inner = raw.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim()
    .replace(/\n+/g, '');
  const viewBox = raw.match(/viewBox="([^"]+)"/)?.[1] ?? '0 0 110 90';
  return { key, inner, viewBox };
});

const body = `/* GENERATED by tools/build-blueprints.mjs — do not edit.
 * Source: design/blueprints/*.svg. Run \`npm run blueprints\` after changing one.
 */
import type { CategoryKey } from './constants';

export type Blueprint = { viewBox: string; inner: string };

export const BLUEPRINTS: Record<CategoryKey, Blueprint> = {
${entries.map((e) => `  ${e.key}: {\n    viewBox: ${JSON.stringify(e.viewBox)},\n    inner: ${JSON.stringify(e.inner)},\n  },`).join('\n')}
};
`;

writeFileSync(OUT, body);
console.log(`wrote lib/blueprints.generated.ts — ${entries.length} plates`);
