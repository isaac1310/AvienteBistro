#!/usr/bin/env node
/**
 * design/kids/*.svg → lib/kidsArt.generated.ts
 *
 * The kids' section was built out of emoji — 🧸 🐶 🐱 🐘 🐰 for the day hosts and 🦋
 * for the decoration. Emoji are somebody else's artwork in somebody else's font, and
 * on a Samsung Ultra the butterflies did not appear at all. Rather than guess at
 * which platform renders which codepoint, the drawings are ours now, in the same
 * 64×64 stroke grammar as the blueprint plates and the nav icons.
 *
 * Seven animals, because the week runs Sunday to Saturday.
 *
 *   npm run kids-art
 */
import { writeFileSync } from 'node:fs';
import { readSvgDir } from './lib/inline-svg.mjs';

const KEYS = [
  'bear', 'dog', 'cat', 'elephant', 'rabbit', 'fox', 'owl',   // one per day
  'butterfly', 'balloon', 'child',                            // decoration
];

const dir = new URL('../design/kids/', import.meta.url).pathname;
const out = new URL('../lib/kidsArt.generated.ts', import.meta.url).pathname;
const entries = readSvgDir(dir, KEYS);

writeFileSync(out, `/* GENERATED by tools/build-kids-art.mjs — do not edit.
 * Source: design/kids/*.svg. Run \`npm run kids-art\` after changing one.
 */

export type KidsArtName = ${KEYS.map((k) => `'${k}'`).join(' | ')};

export const KIDS_ART: Record<KidsArtName, { viewBox: string; inner: string }> = {
${entries.map((e) => `  ${e.key}: {\n    viewBox: ${JSON.stringify(e.viewBox)},\n    inner: ${JSON.stringify(e.inner)},\n  },`).join('\n')}
};
`);
console.log(`wrote lib/kidsArt.generated.ts — ${entries.length} drawings`);
