#!/usr/bin/env node
/**
 * design/motifs/*.svg → lib/motifs.generated.ts
 *
 * A second map beside the category plates, and it exists because the plate generator
 * cannot hold these: `tools/build-blueprints.mjs` KEYS is the nine `CategoryKey`
 * values, and `CategoryPlate` maps them exhaustively. A wine glass or a loaf-shaped
 * loader is not a category, so dropping it in there would either be ignored or break
 * that map.
 *
 * Same drawing language, same inline reason: `currentColor` does not resolve for an
 * SVG loaded as an image, so the markup has to reach the page.
 *
 *   npm run motifs
 */
import { writeFileSync } from 'node:fs';
import { readSvgDir } from './lib/inline-svg.mjs';

const KEYS = [
  /* The blueprint sweep: every one of these replaced an emoji in the chrome. */
  'chef_hat', 'candle', 'apple', 'search', 'folder', 'clipboard', 'link', 'link_off',
  'sparkle',
  'warning',
  'menu_card',
  /* One per course, for the menu card. Five borrow their drawing from the category
     plate of the same food, so a course on the card and its shelf in the book are
     recognisably the same object; only the wine glass had no plate to borrow from.
     `course_pain` is drawn ahead of the course itself, which arrives with 0017. */
  'course_aperitif', 'course_entree', 'course_main',
  'course_sides', 'course_dessert', 'course_pain',
];

const dir = new URL('../design/motifs/', import.meta.url).pathname;
const out = new URL('../lib/motifs.generated.ts', import.meta.url).pathname;
const entries = readSvgDir(dir, KEYS);

writeFileSync(out, `/* GENERATED by tools/build-motifs.mjs — do not edit.
 * Source: design/motifs/*.svg. Run \`npm run motifs\` after changing one.
 */

export type MotifName = ${KEYS.map((k) => `'${k}'`).join(' | ')};

export const MOTIFS: Record<MotifName, { viewBox: string; inner: string }> = {
${entries.map((e) => `  ${e.key}: {\n    viewBox: ${JSON.stringify(e.viewBox)},\n    inner: ${JSON.stringify(e.inner)},\n  },`).join('\n')}
};
`);
console.log(`wrote lib/motifs.generated.ts — ${entries.length} motifs`);
