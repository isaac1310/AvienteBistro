/* Build supabase/seed.sql from the real recipe files in the parent folder.
 *
 *   node tools/seed-from-source.mjs           # report only, writes nothing
 *   node tools/seed-from-source.mjs --commit  # write supabase/seed.sql
 *
 * Dry-run by default, same as the §3.10 migration script it prefigures. The
 * report is the point: it shows exactly what the parser made of each recipe, so
 * a bad rule is visible before it reaches the database.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalizeDocument, UNITS } from '../lib/recipeParse.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const sources = [
  '../my_recipes copy.json',
  '../my_recipes.json',
];

const commit = process.argv.includes('--commit');
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v == null ? 'null' : Number(v));

/* ── read + normalize ──────────────────────────────────────────────────────── */

const all = [];
for (const rel of sources) {
  const path = resolve(root, rel);
  if (!existsSync(path)) { console.error(`  ⚠ missing: ${rel}`); continue; }
  const { recipes, errors } = normalizeDocument(JSON.parse(readFileSync(path, 'utf8')));
  errors.forEach((e) => console.error(`  ✗ ${rel}: ${e}`));
  recipes.forEach((r) => all.push({ ...r, sourceFile: rel.replace('../', '') }));
  console.log(`  ✓ ${rel}: ${recipes.length} recipes`);
}

/* ── report ────────────────────────────────────────────────────────────────── */

console.log(`\n${'─'.repeat(78)}\n${all.length} recipes parsed\n`);

const byCategory = {};
let unitless = 0, ranged = 0, withNote = 0, headed = 0, warned = 0;
const unseen = new Set();

for (const r of all) {
  byCategory[r.category] = (byCategory[r.category] ?? 0) + 1;
  if (r.warnings?.length) warned++;
  for (const i of r.ingredients) {
    if (!i.unit && i.amount == null) unitless++;
    if (i.amountMax != null) ranged++;
    if (i.note) withNote++;
    if (i.unit && !UNITS.includes(i.unit)) unseen.add(i.unit);
  }
  headed += r.steps.filter((s) => s.heading).length;
}

console.log('by category:', byCategory);
console.log(`ingredients: ${all.reduce((a, r) => a + r.ingredients.length, 0)} total · `
  + `${ranged} ranges · ${withNote} with notes · ${unitless} with no quantity`);
console.log(`steps: ${all.reduce((a, r) => a + r.steps.length, 0)} total · ${headed} with headings`);
if (unseen.size) console.error('✗ units outside the enum:', [...unseen]);

for (const r of all) {
  const portion = r.servings ? `serves ${r.servings}` : r.yieldText ?? '—';
  const time = [r.prepMinutes && `prep ${r.prepMinutes}m`, r.cookMinutes && `cook ${r.cookMinutes}m`]
    .filter(Boolean).join(' · ') || 'no times';
  console.log(`\n  ${r.title}${r.titleEn ? `  (${r.titleEn})` : ''}`);
  console.log(`    ${r.category} · ${portion} · ${time} · `
    + `${r.ingredients.length} ingredients · ${r.steps.length} steps`);
  for (const w of r.warnings ?? []) console.log(`    ⚠ ${w}`);
}

/* ── emit ──────────────────────────────────────────────────────────────────── */

const MEMBERS = [
  ['Itzik',  'Papa'],
  ['Moran',  'Maman'],
  ['Savta',  'Savta'],
  ['Saba',   'Saba'],
];

let sql = `-- GENERATED by tools/seed-from-source.mjs — do not edit by hand.
-- Source: ${sources.join(', ')}
-- ${all.length} real family recipes. Re-run the tool to regenerate.
--
-- The two rows with a login are wired up separately: create the users in the
-- Supabase dashboard first (public signup MUST be off), then
--   update family_members set user_id = '<uuid>' where name = 'Itzik';

begin;

insert into family_members (name, display_name) values
${MEMBERS.map(([na, d]) => `  (${q(na)}, ${q(d)})`).join(',\n')};

`;

for (const r of all) {
  const ref = `${r.sourceFile}#${r.externalRef ?? r.title}`;
  sql += `-- ${r.title}\nwith r as (
  insert into recipes (title, title_en, category, description_he, story,
                       serving_suggestions, prep_minutes, cook_minutes,
                       servings, yield_text, external_ref)
  values (${q(r.title)}, ${q(r.titleEn)}, ${q(r.category)}, ${q(r.descriptionHe)},
          ${q(r.story)}, ${q(r.servingSuggestions)}, ${n(r.prepMinutes)}, ${n(r.cookMinutes)},
          ${n(r.servings)}, ${q(r.yieldText)}, ${q(ref)})
  returning id
)
`;
  if (r.ingredients.length) {
    sql += `, ing as (
  insert into ingredients (recipe_id, position, name, amount, amount_max, unit, note)
  select r.id, v.* from r, (values
${r.ingredients.map((i) => `    (${i.position}, ${q(i.name)}, ${n(i.amount)}, ${n(i.amountMax)}, ${q(i.unit)}, ${q(i.note)})`).join(',\n')}
  ) as v(position, name, amount, amount_max, unit, note)
)
`;
  }
  sql += `insert into steps (recipe_id, position, heading, body)
select r.id, v.* from r, (values
${r.steps.map((s) => `  (${s.position}, ${q(s.heading)}, ${q(s.body)})`).join(',\n')}
) as v(position, heading, body);

`;
}

sql += `-- attribute everything to Savta for now; adjust per recipe in the app.
update recipes set source_member_id = (select id from family_members where name = 'Savta')
 where source_member_id is null;

commit;
`;

if (commit) {
  const out = resolve(root, 'supabase/seed.sql');
  writeFileSync(out, sql, 'utf8');
  console.log(`\n✓ wrote supabase/seed.sql (${(sql.length / 1024).toFixed(1)} KB)`);
} else {
  console.log(`\n(dry run — ${(sql.length / 1024).toFixed(1)} KB of SQL not written; pass --commit)`);
}

if (warned) console.log(`\n⚠ ${warned} recipe(s) carry warnings — see above.`);
